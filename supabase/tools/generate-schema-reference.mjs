// Generates docs/database/schema-reference.md from the real catalogue after applying every migration.
// The reference therefore cannot drift from the migrations. Run: npm run schema:docs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDatabase } from './run-db.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.resolve(here, '../../docs/database/schema-reference.md');

const groups = [
  ['Identity and privacy', ['profiles', 'phone_numbers', 'user_consents']],
  ['Contacts and safety', ['contacts', 'contact_requests', 'contact_groups', 'contact_group_members', 'user_blocks', 'abuse_reports']],
  ['Conversations and messages', ['conversations', 'conversation_members', 'messages', 'message_hides', 'message_segments']],
  ['Delivery and SMS', ['message_deliveries', 'message_delivery_events', 'provider_webhooks', 'sms_routes', 'sms_opt_outs', 'sms_country_capabilities', 'provider_configurations']],
  ['Credits', ['messaging_credits', 'credit_transactions']],
  ['Notifications', ['notification_preferences', 'notifications']],
  ['AI', ['ai_assistance_logs']],
  ['Platform and audit', ['system_settings', 'rate_limit_counters', 'audit_logs']],
];

const db = await buildDatabase({ quiet: true });
const q = async (sql, params = []) => (await db.query(sql, params)).rows;
const cell = (value) => String(value ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

const tables = (
  await q(`select c.oid, c.relname, c.relrowsecurity, obj_description(c.oid, 'pg_class') as comment
             from pg_class c join pg_namespace n on n.oid = c.relnamespace
            where n.nspname = 'public' and c.relkind = 'r' order by c.relname`)
).reduce((acc, t) => ({ ...acc, [t.relname]: t }), {});

const listed = new Set(groups.flatMap(([, names]) => names));
const unlisted = Object.keys(tables).filter((t) => !listed.has(t));
if (unlisted.length) groups.push(['Other', unlisted]);
const missing = [...listed].filter((t) => !tables[t]);
if (missing.length) throw new Error(`Generator lists tables that do not exist: ${missing.join(', ')}`);

const out = [];
out.push('# Schema Reference (generated)');
out.push('');
out.push('**Document:** CHKR-DB-006  ');
out.push('**Project:** Chikka Reborn  ');
out.push('**Status:** Generated. Do not edit by hand.  ');
out.push('');
out.push('Generated by `supabase/tools/generate-schema-reference.mjs` from the migrations in `supabase/migrations/`. Regenerate with `npm run schema:docs` in `supabase/tools`. Purpose and design rationale for each table are in [database-schema.md](database-schema.md); policies are in [row-level-security.md](row-level-security.md).');
out.push('');
out.push(`${Object.keys(tables).length} tables. Row Level Security is enabled on every table.`);
out.push('');

for (const [groupName, names] of groups) {
  out.push(`## ${groupName}`);
  out.push('');
  for (const name of names) {
    const t = tables[name];
    out.push(`### \`${name}\``);
    out.push('');
    out.push(`**Purpose:** ${t.comment ?? '(see database-schema.md)'}`);
    out.push('');

    const columns = await q(
      `select a.attnum, a.attname, format_type(a.atttypid, a.atttypmod) as type, a.attnotnull,
              pg_get_expr(d.adbin, d.adrelid) as default_expr, a.attgenerated
         from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
        where a.attrelid = $1 and a.attnum > 0 and not a.attisdropped order by a.attnum`,
      [t.oid],
    );
    const constraints = await q(
      `select conname, contype, pg_get_constraintdef(oid) as def, conkey
         from pg_constraint where conrelid = $1 order by contype, conname`,
      [t.oid],
    );
    const colNames = Object.fromEntries(columns.map((c) => [c.attnum, c.attname]));
    const pkCols = new Set(constraints.filter((c) => c.contype === 'p').flatMap((c) => c.conkey.map((k) => colNames[k])));
    const fkByCol = {};
    for (const c of constraints.filter((x) => x.contype === 'f')) {
      const target = c.def.replace(/^FOREIGN KEY \([^)]*\) REFERENCES /, '');
      for (const k of c.conkey) fkByCol[colNames[k]] = target;
    }

    out.push('| Column | Type | Required | Default | Key / reference |');
    out.push('|---|---|---|---|---|');
    for (const c of columns) {
      const keys = [];
      if (pkCols.has(c.attname)) keys.push('PK');
      if (fkByCol[c.attname]) keys.push(`FK → ${fkByCol[c.attname]}`);
      const def = c.attgenerated ? `generated: ${c.default_expr}` : (c.default_expr ?? '');
      out.push(`| \`${c.attname}\` | ${cell(c.type)} | ${c.attnotnull ? 'yes' : 'no'} | ${cell(def)} | ${cell(keys.join('; '))} |`);
    }
    out.push('');

    const uniques = constraints.filter((c) => c.contype === 'u');
    const uniqueIdx = await q(
      `select indexname, indexdef from pg_indexes
        where schemaname = 'public' and tablename = $1 and indexdef like 'CREATE UNIQUE INDEX%'
          and indexname not in (select conname from pg_constraint where conrelid = $2)`,
      [name, t.oid],
    );
    if (uniques.length || uniqueIdx.length) {
      out.push('**Unique rules**');
      out.push('');
      for (const u of uniques) out.push(`- \`${u.conname}\`: \`${u.def}\``);
      for (const u of uniqueIdx) out.push(`- \`${u.indexname}\`: \`${u.indexdef.replace(/^CREATE UNIQUE INDEX \S+ ON public\.\S+ /, '')}\``);
      out.push('');
    }

    const checks = constraints.filter((c) => c.contype === 'c');
    if (checks.length) {
      out.push('**Check constraints**');
      out.push('');
      for (const c of checks) out.push(`- \`${c.conname}\`: \`${c.def.replace(/^CHECK /, '').replace(/\s+/g, ' ')}\``);
      out.push('');
    }

    const fks = constraints.filter((c) => c.contype === 'f');
    if (fks.length) {
      out.push('**Foreign keys**');
      out.push('');
      for (const f of fks) out.push(`- \`${f.conname}\`: \`${f.def.replace(/^FOREIGN KEY /, '')}\``);
      out.push('');
    }

    const indexes = await q(
      `select indexname, indexdef from pg_indexes
        where schemaname = 'public' and tablename = $1 and indexdef not like 'CREATE UNIQUE INDEX%'
        order by indexname`,
      [name],
    );
    if (indexes.length) {
      out.push('**Indexes**');
      out.push('');
      for (const i of indexes) out.push(`- \`${i.indexname}\`: \`${i.indexdef.replace(/^CREATE INDEX \S+ ON public\.\S+ /, '')}\``);
      out.push('');
    }

    const triggers = await q(
      `select tgname, pg_get_triggerdef(oid) as def from pg_trigger where tgrelid = $1 and not tgisinternal order by tgname`,
      [t.oid],
    );
    if (triggers.length) {
      out.push('**Triggers**');
      out.push('');
      for (const g of triggers) {
        const when = g.def.replace(/^CREATE TRIGGER \S+ /, '').replace(/ ON public\.\S+/, '').replace(/ FOR EACH ROW EXECUTE FUNCTION /, ' → ');
        out.push(`- \`${g.tgname}\`: ${when}`);
      }
      out.push('');
    }

    const policies = await q(
      `select policyname, cmd, roles from pg_policies where schemaname = 'public' and tablename = $1 order by policyname`,
      [name],
    );
    out.push(`**Row Level Security:** enabled. ${policies.length ? `Policies: ${policies.map((p) => `\`${p.policyname}\` (${p.cmd.toLowerCase()})`).join(', ')}.` : 'No policies: no client access (server-only).'}`);
    out.push('');
  }
}

out.push('## Views');
out.push('');
const views = await q(`select viewname from pg_views where schemaname = 'public' order by viewname`);
for (const v of views) {
  const cols = await q(`select column_name from information_schema.columns where table_schema = 'public' and table_name = $1 order by ordinal_position`, [v.viewname]);
  out.push(`- \`${v.viewname}\`: columns ${cols.map((c) => `\`${c.column_name}\``).join(', ')}.`);
}
out.push('');
out.push('## Functions (schema `private`, not exposed over the API)');
out.push('');
out.push('| Function | Kind | Callable by |');
out.push('|---|---|---|');
const fns = await q(
  `select p.proname, pg_get_function_identity_arguments(p.oid) as args, p.prorettype::regtype::text as ret, p.prosecdef,
          has_function_privilege('authenticated', p.oid, 'execute') as auth_exec,
          has_function_privilege('service_role', p.oid, 'execute') as svc_exec
     from pg_proc p join pg_namespace n on n.oid = p.pronamespace where n.nspname = 'private' order by p.proname`,
);
for (const f of fns) {
  const kind = f.ret === 'trigger' ? 'trigger function' : (f.prosecdef ? 'security definer' : 'function');
  const who = [f.auth_exec ? 'authenticated' : null, f.svc_exec ? 'service_role' : null].filter(Boolean).join(', ') || 'triggers only';
  out.push(`| \`${f.proname}(${cell(f.args)})\` | ${kind} | ${who} |`);
}
out.push('');

fs.writeFileSync(outFile, out.join('\n'));
console.log(`Wrote ${path.relative(process.cwd(), outFile)} (${out.length} lines)`);
